import assert from 'node:assert/strict';
import { decodeLook, encodeLook, equipItem, newProfile, sanitizeEquipment, outfitOf } from '../dist/index.js';
const original = newProfile({ x: 40, y: 40 });
assert.equal(original.equipment.weapon, 'staff-bell');
const equip = equipItem(original, 'weapon', 'staff-bone');
assert.equal(equip.ok, true);
assert.equal(equip.profile.equipment.weapon, 'staff-bone');
assert.equal(original.equipment.weapon, 'staff-bell', 'transaction must not mutate original');
assert.equal(equipItem(original, 'head', 'staff-bone').ok, false);
assert.equal(equipItem({ ...original, stacks: [] }, 'weapon', 'staff-bone').ok, false);
assert.equal(equipItem(original, '__proto__', 'staff-bell').ok, false);
assert.equal(equipItem(original, 'weapon', null).profile.equipment.weapon, undefined);
const look = { body: 'robe-bronze-ward', weapon: 'staff-bone', head: 'hat-ngob' };
assert.deepEqual(decodeLook(encodeLook(look)), { weapon: 'staff-bone', head: 'hat-ngob' });
assert.equal(equipItem(original, 'body', 'robe-bronze-ward').error, 'art-unavailable');
assert.deepEqual(decodeLook('body:robe-bronze-ward'), {}, 'stale clients cannot restore rejected art');
const stale = structuredClone(original); stale.equipment.body = 'robe-bronze-ward';
assert.equal(sanitizeEquipment(stale).equipment.body, undefined);
assert.deepEqual(decodeLook('head:staff-bell,weapon:unknown,waist:hat-ngob,__proto__:x'), {});
assert.equal(outfitOf(look), 'base', 'rejected outfit preserves original identity');
assert.equal(outfitOf({}), 'base');
const sold = structuredClone(equip.profile);
sold.stacks = sold.stacks.filter(s => s.itemId !== 'staff-bone');
assert.equal(sanitizeEquipment(sold).equipment.weapon, undefined);
console.log('equipment: ownership, slot validation, immutable equip/unequip, sanitized synced look');
