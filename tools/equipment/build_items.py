"""Package equipment layer art and preview the fit (docs/design/equipment/README.md).

Input:  docs/design/equipment/raw/<id>/<facing>.png (PixelLab 8 views), docs/design/equipment/items.json
Output: apps/client/public/assets/equipment/<id>/<facing>.png (cropped, native pixels) + manifest.json with each
        view's pivot; inventory icons apps/client/public/assets/ui/items/<id>.png.
Pivot per slot: head = bottom-centre of the brim; body = centre x, 35% down; waist and weapon = bounding-box centre.
Run:    python -I tools/equipment/build_items.py [--preview out.png [anim] [frame]]
The preview composes items on both bodies in all 8 facings with the same maths as the client (EquipmentLayers.ts):
item pivot -> body landmark + per-body offset, all at the rig's native scale.
"""
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / 'docs/design/equipment/raw'
OUT = ROOT / 'apps/client/public/assets/equipment'
ICONS = ROOT / 'apps/client/public/assets/ui/items'
RIG = ROOT / 'apps/client/public/assets/pixellab'
FACINGS = ['south', 'south-east', 'east', 'north-east', 'north', 'north-west', 'west', 'south-west']


def pivot(slot: str, w: int, h: int) -> dict:
    if slot == 'head':
        return {'x': w / 2, 'y': h}
    if slot == 'body':
        return {'x': w / 2, 'y': round(h * 0.35, 1)}
    return {'x': w / 2, 'y': h / 2}


def shared_visuals() -> dict:
    """EQUIPMENT_VISUALS from packages/shared/src/equipment.ts (the client's source of truth), parsed for the preview."""
    src = (ROOT / 'packages/shared/src/equipment.ts').read_text(encoding='utf-8')
    out = {}
    for m in re.finditer(r"'([a-z-]+)': \{ slot: '(\w+)', anchor: '(\w+)', offset: (.+?)(?:, scale: ([\d.]+))? \},\n", src):
        item, slot, anchor, off, scale = m.groups()
        same = re.match(r'same\((-?[\d.]+), (-?[\d.]+)\)', off)
        if same:
            o = {b: {'x': float(same[1]), 'y': float(same[2])} for b in ('male', 'female')}
        else:
            o = {b: {'x': float(x), 'y': float(y)} for b, x, y in re.findall(r'(male|female): \{ x: (-?[\d.]+), y: (-?[\d.]+) \}', off)}
        out[item] = {'slot': slot, 'anchor': anchor, 'offset': o, 'scale': float(scale or 1)}
    return out


def main():
    spec = json.loads((ROOT / 'docs/design/equipment/items.json').read_text(encoding='utf-8'))['items']
    manifest = {'note': 'Generated by tools/equipment/build_items.py; images are native-density pixels, drawn at the rig scale.', 'items': {}}
    for item_id, it in spec.items():
        if it.get('status', '').startswith('superseded'):
            continue
        if not all((RAW / item_id / f'{f}.png').exists() for f in FACINGS):
            print('skip (views missing):', item_id)
            continue
        views = {}
        for f in FACINGS:
            img = Image.open(RAW / item_id / f'{f}.png').convert('RGBA')
            box = img.getchannel('A').point(lambda a: 255 if a > 20 else 0).getbbox()
            img = img.crop((max(0, box[0] - 1), max(0, box[1] - 1), min(img.width, box[2] + 1), min(img.height, box[3] + 1)))
            (OUT / item_id).mkdir(parents=True, exist_ok=True)
            img.save(OUT / item_id / f'{f}.png')
            views[f] = {'image': f'{item_id}/{f}.png', 'width': img.width, 'height': img.height, 'pivot': pivot(it['slot'], img.width, img.height)}
            if f == 'south':
                icon = Image.new('RGBA', (64, 64))
                fit = img.copy()
                fit.thumbnail((56, 56), Image.NEAREST)
                icon.alpha_composite(fit, ((64 - fit.width) // 2, (64 - fit.height) // 2))
                icon.save(ICONS / f'{item_id}.png')
        manifest['items'][item_id] = {'slot': it['slot'], 'views': views}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print('built', ', '.join(manifest['items']))
    if '--preview' in sys.argv:
        i = sys.argv.index('--preview')
        preview(manifest, sys.argv[i + 1], sys.argv[i + 2] if len(sys.argv) > i + 2 else 'static', int(sys.argv[i + 3]) if len(sys.argv) > i + 3 else 0)


def preview(manifest: dict, out: str, anim: str, frame: int):
    visuals = shared_visuals()
    rig = json.loads((RIG / 'main-v1-manifest.json').read_text(encoding='utf-8'))
    anchors = json.loads((RIG / 'main-v1-anchors.json').read_text(encoding='utf-8'))['bodies']
    sets = [['hat-ngob', 'collar-jade', 'sash-red', 'staff-bell'], ['hat-ritual', 'collar-bronze', 'belt-talisman', 'staff-bone']]
    cell = 180
    sheet = Image.new('RGBA', (cell * 8, cell * 4), (40, 60, 55, 255))
    stack = {'waist': 1, 'body': 2, 'head': 3, 'weapon': 4}
    for row, (body, look) in enumerate([(b, s) for s in sets for b in ('male', 'female')]):
        for col, facing in enumerate(FACINGS):
            if anim == 'static':
                img = Image.open(RIG / rig['bodies'][body]['frames'][facing]['image']).convert('RGBA')
                pts = anchors[body]['static'][facing]
            else:
                paths = rig['bodies'][body]['animations'][anim]['frames'].get(facing)
                if not paths:
                    continue
                k = frame % len(paths)
                img = Image.open(RIG / paths[k]).convert('RGBA')
                pts = anchors[body][anim][facing][k]
            ox, oy = col * cell + (cell - img.width) // 2, row * cell + (cell - img.height)
            layers = []
            for item_id in look:
                v, m = visuals.get(item_id), manifest['items'].get(item_id)
                if not v or not m:
                    continue
                view = m['views'][facing]
                ax, ay = pts[v['anchor']]
                off = v['offset'][body]
                sc = v['scale']
                x = ox + ax + off['x'] - view['pivot']['x'] * sc
                y = oy + ay + off['y'] - view['pivot']['y'] * sc
                behind = v['slot'] == 'weapon' and facing in ('south', 'south-east', 'south-west', 'east', 'west')
                li = Image.open(OUT / view['image']).convert('RGBA')
                if sc != 1:
                    li = li.resize((max(1, round(li.width * sc)), max(1, round(li.height * sc))), Image.NEAREST)
                layers.append((-1 if behind else stack[v['slot']], li, (round(x), round(y))))
            for _, li, pos in sorted([l for l in layers if l[0] < 0], key=lambda l: l[0]):
                sheet.alpha_composite(li, pos)
            sheet.alpha_composite(img, (ox, oy))
            for _, li, pos in sorted([l for l in layers if l[0] >= 0], key=lambda l: l[0]):
                sheet.alpha_composite(li, pos)
    sheet.save(out)


if __name__ == '__main__':
    main()
