"""Per-frame body anchors for equipment layers (docs/design/equipment/README.md).

The main characters are flattened PixelLab sprites, so equipment cannot be cut out of them. Instead each item is a
separate layer attached to body landmarks found in every runtime frame from its silhouette:
- head 17%, neck 34%, waist 53% of the figure height (see BANDS), x = median opaque column in that band;
- crown: the top of the figure at the head's x (where a hat sits); feet: the soles.
Points are in the frame image's own pixel coordinates (top-left origin), exactly as the client draws it.

Input:  apps/client/public/assets/pixellab/main-v1-manifest.json (static rotations, walk, idle, attack frames)
        apps/client/public/assets/skills/medium-v1/manifest.json (cast pose sheets)
Output: apps/client/public/assets/pixellab/main-v1-anchors.json
Run:    python -I tools/equipment/build_anchors.py [--preview out.png]
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
RIG = ROOT / 'apps/client/public/assets/pixellab'
SKILLS = ROOT / 'apps/client/public/assets/skills/medium-v1'


# Fractions of the figure height (top of hair to the soles), measured on the static rotations of both bodies. A first
# attempt found the neck as the narrowest row, but long hair and feathers make the chin narrower than the neck, so the
# chibi proportions are used instead.
BANDS = {'head': 0.17, 'neck': 0.34, 'waist': 0.53}


def landmarks(img: Image.Image) -> dict:
    a = np.asarray(img.convert('RGBA'))[..., 3] > 40
    ys, xs = np.nonzero(a)
    top, bottom = int(ys.min()), int(ys.max())
    h = bottom - top + 1

    def band_x(y: int) -> float:
        # Median column of the opaque pixels near this row: robust to hair, ribbons and feathers sticking out.
        cols = np.nonzero(a[max(0, y - 2):y + 3])[1]
        return float(np.median(cols)) if cols.size else float(np.median(xs))

    pts = {name: (band_x(top + int(f * h)), top + int(f * h)) for name, f in BANDS.items()}
    return {
        'crown': [round(pts['head'][0], 1), top],
        **{k: [round(x, 1), y] for k, (x, y) in pts.items()},
        'feet': [round(band_x(bottom - 2), 1), bottom],
    }


def main():
    rig = json.loads((RIG / 'main-v1-manifest.json').read_text(encoding='utf-8'))
    skills = json.loads((SKILLS / 'manifest.json').read_text(encoding='utf-8-sig'))
    out = {'note': 'Generated by tools/equipment/build_anchors.py; points are frame-image pixels.', 'bodies': {}}
    for body, entry in rig['bodies'].items():
        b = {'static': {d: landmarks(Image.open(RIG / f['image'])) for d, f in entry['frames'].items()}}
        for anim, info in entry.get('animations', {}).items():
            b[anim] = {d: [landmarks(Image.open(RIG / p)) for p in paths] for d, paths in info['frames'].items()}
        cast = {}
        for facing, sheet in skills['casts'].get(body, {}).items():
            img = Image.open(SKILLS / sheet['image'])
            cells = [img.crop((i * sheet['width'], 0, (i + 1) * sheet['width'], sheet['height'])) for i in range(sheet['frames'])]
            cast[facing] = [landmarks(c) for c in cells]
        b['cast'] = cast
        out['bodies'][body] = b
    (RIG / 'main-v1-anchors.json').write_text(json.dumps(out, separators=(',', ':')) + '\n', encoding='utf-8')
    print('anchors:', {b: sum(len(v) if isinstance(v, list) else 1 for a in d.values() for v in a.values()) for b, d in out['bodies'].items()}, 'frames')

    if '--preview' in sys.argv:
        # Static rotations with their landmarks drawn, for visual review.
        dirs = ['south', 'south-east', 'east', 'north-east', 'north', 'north-west', 'west', 'south-west']
        sheet = Image.new('RGBA', (128 * 8, 128 * 2), (40, 60, 55, 255))
        for r, body in enumerate(rig['bodies']):
            for c, d in enumerate(dirs):
                img = Image.open(RIG / rig['bodies'][body]['frames'][d]['image']).convert('RGBA')
                sheet.alpha_composite(img, (c * 128, r * 128))
                draw = ImageDraw.Draw(sheet)
                for name, colour in (('crown', 'yellow'), ('head', 'cyan'), ('neck', 'red'), ('waist', 'magenta'), ('feet', 'white')):
                    x, y = out['bodies'][body]['static'][d][name]
                    draw.rectangle((c * 128 + x - 1, r * 128 + y - 1, c * 128 + x + 1, r * 128 + y + 1), fill=colour)
        sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(sys.argv[sys.argv.index('--preview') + 1])


if __name__ == '__main__':
    main()
