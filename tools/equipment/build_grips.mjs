// Grip x per weapon view: weapon art is not centred on its shaft (hanging charms, axe heads, bow strings), so the hand
// would miss the handle if the image were centred on it. For every weapon and off-hand art in EQUIPMENT_VISUALS and
// each facing, find the widest opaque run at the grip row (grip fraction of the height) and store
// its centre as a fraction of the width. Output: apps/client/public/assets/equipment/grips.json (client origin x).
// Run after build_weapons.mjs: node tools/equipment/build_grips.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { sharp } from '../rig/body-eight-lib.mjs';

const ROOT = new URL('../../', import.meta.url);
const p = (rel) => fileURLToPath(new URL(rel, ROOT));
const FACINGS = ['south', 'south-east', 'east', 'north-east', 'north', 'north-west', 'west', 'south-west'];
const src = await readFile(p('packages/shared/src/equipment.ts'), 'utf8');
const arts = new Map();
for (const line of src.split(/\r?\n/)) {
  const m = /^\s*'([a-z-]+)': \{ slot: 'weapon', kind: 'weapon', grip: ([\d.]+)/.exec(line);
  if (!m) continue;
  arts.set(m[1], +m[2]);
  const off = /offhand: \{ art: '([a-z-]+)', grip: ([\d.]+)/.exec(line);
  if (off) arts.set(off[1], +off[2]);
}
const out = {};
for (const [art, grip] of arts) {
  out[art] = {};
  for (const f of FACINGS) {
    const file = p(`apps/client/public/assets/equipment/${art}/${f}.png`);
    if (!existsSync(file)) continue;
    const { data, info } = await sharp(await readFile(file)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    // Search a few rows around the grip row in case the handle is thin or broken there.
    const row0 = Math.min(info.height - 1, Math.round(grip * info.height));
    let best = null;
    for (const dy of [0, -1, 1, -2, 2]) {
      const y = row0 + dy;
      if (y < 0 || y >= info.height) continue;
      const runs = [];
      let start = -1;
      for (let x = 0; x <= info.width; x++) {
        const solid = x < info.width && data[(y * info.width + x) * 4 + 3] > 20;
        if (solid && start < 0) start = x;
        if (!solid && start >= 0) { runs.push([start, x - 1]); start = -1; }
      }
      for (const [a, b] of runs) {
        // The handle is the widest run at the grip row (strings, charms and cords are thinner); ties: nearest the centre.
        const c = (a + b + 1) / 2, d = Math.abs(c - info.width / 2), w = b - a + 1;
        if (!best || w > best.w || (w === best.w && d < best.d)) best = { c, d, w };
      }
      if (best) break;
    }
    out[art][f] = +((best ? best.c : info.width / 2) / info.width).toFixed(3);
  }
}
await writeFile(p('apps/client/public/assets/equipment/grips.json'), JSON.stringify({ note: 'Generated by tools/equipment/build_grips.mjs: grip x as a fraction of each view width.', grips: out }, null, 1) + '\n');
console.log(`grips: ${arts.size} arts`);
