"""Package the modular rig (v2): body/outfit sprite strips on the shared skeletons + per-frame layer data.

Input:  docs/design/rig/raw/<body>/<outfit>/<anim>/<facing>/<n>.png  (tools/rig/animate_skeleton.ps1)
        docs/design/rig/skeletons.json                                 (tools/rig/skeleton.py)
Output: apps/client/public/assets/rig-v2/<body>/<outfit>/<anim>-<facing>.png (frames left to right, 128 px)
        apps/client/public/assets/rig-v2/manifest.json:
          bodies.<body>.outfits.<outfit>.<anim>.<facing> = frame count (only complete sets are listed)
          bodies.<body>.layers.<anim>.<facing>[frame] = { grip, tip, front, head: [x, y], crown: [x, y], tilt }
All points are frame pixels; every outfit shares the same skeletons, so the layer data is per body, not per outfit.
Run: python -I tools/rig/build_rig_v2.py
"""
import json
import math
import os
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / 'docs/design/rig/raw'
OUT = ROOT / 'apps/client/public/assets/rig-v2'
sys.path.insert(0, str(ROOT / 'tools/sprites'))
from rig_cleanup import drop_specks  # noqa: E402

FRAME = 128
FACINGS = ['south', 'south-east', 'east', 'north-east', 'north', 'north-west', 'west', 'south-west']
FPS = {'idle': 5, 'walk': 12, 'attack': 16, 'cast': 12}


def head_data(kps):
    k = {p['label']: (p['x'] * FRAME, p['y'] * FRAME) for p in kps}
    ear = ((k['RIGHT EAR'][0] + k['LEFT EAR'][0]) / 2, (k['RIGHT EAR'][1] + k['LEFT EAR'][1]) / 2)
    neck = k['NECK']
    up = (ear[0] - neck[0], ear[1] - neck[1])
    length = math.hypot(*up) or 1
    # The crown sits about one ear-to-neck distance above the ears (chibi head).
    crown = (ear[0] + up[0] / length * length * 0.9, ear[1] + up[1] / length * length * 0.9)
    tilt = math.degrees(math.atan2(up[0], -up[1]))  # 0 = upright
    return [round(ear[0], 1), round(ear[1], 1)], [round(crown[0], 1), round(crown[1], 1)], round(tilt, 1)


def main():
    skel = json.loads((ROOT / 'docs/design/rig/skeletons.json').read_text(encoding='utf-8'))['bodies']
    manifest = {'note': 'Generated by tools/rig/build_rig_v2.py. Frames are 128 px; points are frame pixels.', 'frame': FRAME, 'fps': FPS, 'bodies': {}}
    report = []
    for body_dir in sorted(p for p in RAW.iterdir() if p.is_dir()):
        body = body_dir.name
        b = {'outfits': {}, 'layers': {}}
        for outfit_dir in sorted(p for p in body_dir.iterdir() if p.is_dir()):
            outfit = outfit_dir.name
            if outfit != 'base':
                continue  # Archived: rejected identity-changing full-body outfits.
            o = {}
            for anim in FPS:
                expected = len(skel[body]['south'][anim])
                done = {}
                for facing in FACINGS:
                    folder = outfit_dir / anim / facing
                    frames = sorted(folder.glob('*.png'), key=lambda p: int(p.stem)) if folder.exists() else []
                    if len(frames) < expected:
                        report.append(f'{body}/{outfit}/{anim}/{facing}: {len(frames)}/{expected} frames')
                        continue
                    strip = Image.new('RGBA', (FRAME * expected, FRAME))
                    for i, f in enumerate(frames[:expected]):
                        img = drop_specks(Image.open(f), 12)[0]
                        if img.size != (FRAME, FRAME):
                            raise SystemExit(f'{f}: expected {FRAME}x{FRAME}, got {img.size}')
                        strip.alpha_composite(img, (i * FRAME, 0))
                    (OUT / body / outfit).mkdir(parents=True, exist_ok=True)
                    strip.save(OUT / body / outfit / f'{anim}-{facing}.png')
                    done[facing] = expected
                if done:
                    o[anim] = done
            b['outfits'][outfit] = o
        for anim in FPS:
            b['layers'][anim] = {}
            for facing in FACINGS:
                frames = []
                for kps, w in zip(skel[body][facing][anim], skel[body][facing][anim + ':weapon']):
                    head, crown, tilt = head_data(kps)
                    frames.append({**w, 'head': head, 'crown': crown, 'tilt': tilt})
                b['layers'][anim][facing] = frames
        manifest['bodies'][body] = b
    OUT.mkdir(parents=True, exist_ok=True)
    pending=OUT/f'manifest.{os.getpid()}.tmp'
    pending.write_text(json.dumps(manifest, separators=(',', ':')) + '\n', encoding='utf-8')
    pending.replace(OUT/'manifest.json')
    # Inventory icon uses the retained outfit rotation, never an invented clothing overlay.
    for outfit_dir in (ROOT / 'docs/design/rig/outfits').iterdir():
        source = outfit_dir / 'male/south.png'
        if not source.exists():
            continue
        image = Image.open(source).convert('RGBA')
        image.thumbnail((56, 56), Image.NEAREST)
        icon = Image.new('RGBA', (64, 64))
        icon.alpha_composite(image, ((64-image.width)//2, (64-image.height)//2))
        icon.save(ROOT / f'apps/client/public/assets/ui/items/robe-{outfit_dir.name}.png')
    for body, b in manifest['bodies'].items():
        for outfit, o in b['outfits'].items():
            complete = sum(len(v) for v in o.values())
            print(f'{body}/{outfit}: {complete}/32 animation-facings complete')
    if report:
        print('incomplete:', len(report), '(first:', report[0], ')')


if __name__ == '__main__':
    main()
