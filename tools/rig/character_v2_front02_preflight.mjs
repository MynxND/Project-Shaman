import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const root = new URL('../../', import.meta.url);
const json = async path => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const stage = 'docs/design/character-v2/body-front-02/';
const request = await json(`${stage}request.json`);
const authorization = await json(`${stage}authorization.json`);
const ledger = await json('docs/design/character-v2/cost-ledger.json');
const manifest = await json('apps/client/public/assets/character-v2/manifest.json');
assert.equal(authorization.id, 'body-front-02');
assert.equal(authorization.maxSubmissions, 1);
assert.equal(authorization.maxCredits, 6);
for (const field of ['rotationAuthorized', 'hairAuthorized', 'outfitAuthorized', 'retryAuthorized', 'visualApproved']) assert.equal(authorization[field], false);
assert.equal(request.tool, 'create_image_pro_flash');
assert.equal(request.arguments.width, 128);
assert.equal(request.arguments.height, 128);
assert.equal(request.arguments.no_background, true);
assert.ok(request.arguments.description.length <= 2000);
assert.match(request.arguments.description, /3.5 HEADS TOTAL/);
assert.match(request.arguments.description, /SHORT COMPACT TORSO, SHORT LEGS/);
assert.match(request.arguments.description, /NO abs/);
assert.equal(request.referencePath, 'docs/design/pixellab-main/male-south-ref.png');
assert.equal(ledger.cap, 18);
assert.equal(ledger.acceptedSpec, true);
assert.equal(ledger.reserved, 0);
assert.equal(ledger.pendingCredits, 0);
assert.equal(ledger.jobs.filter(job => job.stage === 'body-front-02').length, 0);
assert.equal(ledger.spent, ledger.jobs.reduce((total, job) => total + job.chargedCredits, 0));
assert.ok(ledger.cap - ledger.spent >= 6);
assert.deepEqual(manifest.budget, { cap: ledger.cap, spent: ledger.spent, reserved: ledger.reserved });
assert.equal(manifest.approvals.userVisualAccepted, false);
console.log(`FRONT02 preflight PASS: ${request.arguments.description.length}/2000 prompt chars; prior jobs retained=${ledger.jobs.length}; spent=${ledger.spent}; available=${ledger.cap - ledger.spent}; one new <=6 stage only.`);