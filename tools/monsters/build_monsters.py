"""Pack reviewed PixelLab monster frames into runtime sheets (docs/design/monsters/README.md).

Input:  docs/design/monsters/raw/<id>/<animation>/frame_XX.png (index 00 = the seed, as returned by animate_image)
Output: apps/client/public/assets/monsters/<id>.png (one row per animation, 128 px cells) + manifest.json
Run:    python -I tools/monsters/build_monsters.py
"""
import json
from pathlib import Path
from PIL import Image
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'sprites'))
from rig_cleanup import drop_specks  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / 'docs/design/monsters/raw'
OUT = ROOT / 'apps/client/public/assets/monsters'
# Which generated frames each animation plays (index 0 repeats the seed), its rate and whether it loops.
ANIMS = {
    'idle':   {'first': 0, 'fps': 6,  'loop': True},
    'move':   {'first': 1, 'fps': 10, 'loop': True},
    'attack': {'first': 0, 'fps': 14, 'loop': False},
    'hurt':   {'first': 1, 'fps': 12, 'loop': False},
    'death':  {'first': 0, 'fps': 10, 'loop': False},
}
# Ground point under each monster in its cell (where its shadow sits and its world position is). Walkers stand on the
# bottom of their seed sprite; floating spirits hover this many pixels above the ground point. The Leaf Wisp keeps
# its reviewed anchor.
ANCHORS = {'leaf-wisp': {'x': 64, 'y': 114}}
HOVER = {'spirit-flame': 8}
# Reviewed frame picks (indices into the generated frames, 0 = seed) where some frames were unusable:
# Spirit Flame idle frames 2-3 contained the spat orb (idle would keep spitting); its hurt frame 2 was a symmetric
# white starburst (rejected look, see Amulet Blast v3).
FRAME_PICK = {'spirit-flame': {'idle': [0, 1, 4], 'hurt': [1, 3, 4]}}
# Detached sparkles under this many pixels are removed (tools/sprites/rig_cleanup.py); the Spirit Flame keeps its motes.
KEEP_SPECKS = {'spirit-flame'}


def ground_anchor(monster_id: str, seed: Image.Image) -> dict:
    if monster_id in ANCHORS:
        return ANCHORS[monster_id]
    alpha = seed.getchannel('A').point(lambda a: 255 if a > 40 else 0)
    left, top, right, bottom = alpha.getbbox()
    # x: the silhouette's horizontal centre, so mirroring for west keeps the body in place.
    x = (left + right) // 2
    return {'x': int(x), 'y': int(min(seed.height - 1, bottom + HOVER.get(monster_id, 0)))}


def build(monster_id: str) -> dict:
    seed = Image.open(RAW / monster_id / 'seed.png').convert('RGBA')
    CELL = seed.width
    rows = []
    for name, rule in ANIMS.items():
        frames = sorted((RAW / monster_id / name).glob('frame_*.png'))
        pick = FRAME_PICK.get(monster_id, {}).get(name)
        frames = [frames[i] for i in pick] if pick else frames[rule['first']:]
        if not frames:
            raise SystemExit(f'{monster_id}: missing {name} frames')
        imgs = [Image.open(f).convert('RGBA') for f in frames]
        if monster_id not in KEEP_SPECKS and monster_id != 'leaf-wisp':
            imgs = [drop_specks(im, 12)[0] for im in imgs]
        for f, im in zip(frames, imgs):
            if im.size != (CELL, CELL):
                raise SystemExit(f'{f}: expected {CELL}x{CELL}, got {im.size}')
            if im.getchannel('A').getextrema()[0] == 255:
                raise SystemExit(f'{f}: frame is fully opaque (background not removed)')
        rows.append((name, imgs, rule))
    width = max(len(imgs) for _, imgs, _ in rows) * CELL
    sheet = Image.new('RGBA', (width, len(rows) * CELL), (0, 0, 0, 0))
    animations = {}
    for row, (name, imgs, rule) in enumerate(rows):
        for i, im in enumerate(imgs):
            sheet.alpha_composite(im, (i * CELL, row * CELL))
        animations[name] = {'row': row, 'frames': len(imgs), 'fps': rule['fps'], 'loop': rule['loop']}
    OUT.mkdir(parents=True, exist_ok=True)
    sheet.save(OUT / f'{monster_id}.png', optimize=True)
    return {'image': f'{monster_id}.png', 'frameWidth': CELL, 'frameHeight': CELL, 'columns': width // CELL,
            'anchor': ground_anchor(monster_id, seed), 'faces': 'east', 'animations': animations}


def main():
    spec = json.loads((ROOT / 'docs/design/monsters/monsters.json').read_text(encoding='utf-8'))
    ready = [m for m, d in spec['monsters'].items() if not d.get('planned') and (RAW / m / 'death').exists()]
    manifest = {'note': 'Generated by tools/monsters/build_monsters.py from PixelLab frames; sprites face east and are mirrored for west.',
                'monsters': {m: build(m) for m in ready}}
    (OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print('built', ', '.join(ready))


if __name__ == '__main__':
    main()
